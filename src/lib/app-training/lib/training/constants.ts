const normalizeExerciseName = (value: string) => value.trim().toLowerCase();

const exerciseNameVariants = (exercise: Exercise) => [exercise.name, ...(exercise.aliases ?? [])];

export const matchesExerciseName = (exercise: Exercise, candidate: string) => {
  if (!candidate) return false;
  const term = normalizeExerciseName(candidate);
  if (!term) return false;
  return exerciseNameVariants(exercise).some((label) => normalizeExerciseName(label) === term);
};

export const findExerciseByName = (candidate: string) => {
  if (!candidate) return undefined;
  const term = normalizeExerciseName(candidate);
  if (!term) return undefined;
  return EXERCISE_DB.find((exercise) => matchesExerciseName(exercise, term));
};

