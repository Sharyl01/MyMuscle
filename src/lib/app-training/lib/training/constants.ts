export const featuredMuscleKeyFor = (muscle: string | null | undefined) => {
  if (!muscle) return undefined;
  const normalized = muscle.trim().toLowerCase().replace(/_stroke$/, "");
  if (!normalized) return undefined;
  if (FEATURED_SEARCH_EXERCISES_BY_MUSCLE[normalized]) return normalized;
  if (FEATURED_EXERCISES_BY_MUSCLE[normalized]) return normalized;
  const underscored = normalized.replace(/[\s-]+/g, "_");
  if (FEATURED_SEARCH_EXERCISES_BY_MUSCLE[underscored]) return underscored;
  if (FEATURED_EXERCISES_BY_MUSCLE[underscored]) return underscored;
  const base = underscored.replace(/_(l|r)$/, "");
  return (
    FEATURED_MUSCLE_ALIASES[normalized] ??
    FEATURED_MUSCLE_ALIASES[underscored] ??
    FEATURED_MUSCLE_ALIASES[base] ??
    base
  );
};

export const featuredExerciseIdsForMuscle = (muscle: string | null | undefined) => {
  const key = featuredMuscleKeyFor(muscle);
  return key
    ? (
        FEATURED_SEARCH_EXERCISES_BY_MUSCLE[key] ??
        FEATURED_EXERCISES_BY_MUSCLE[key] ??
        []
      ).slice(0, 10)
    : [];
};
